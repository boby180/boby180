def _norm(word: str) -> list[str]:
    """Search forms of a word: lower case, [n] indexes split off, Hebrew prefixes stripped, synonyms."""
    w = word.lower().strip()
    out = set()
    m = re.fullmatch(r"([a-z]{2})\[?(\d)\]?", w)
    if m:                       # KI[2] -> ki, ki2
        out |= {m.group(1), m.group(1) + m.group(2)}
    w = re.sub(r"[\[\]\"'.,:;?!()]", "", w)
    if not w:
        return []
    out.add(w)
    for p in _PREFIXES:
        if w.startswith(p) and len(w) - len(p) >= 2:
            out.add(w[len(p):])
    for f in list(out):
        if f in SYNONYMS:
            out.add(SYNONYMS[f])
    return [f for f in out if f not in _STOP]


def _words(text: str) -> list[str]:
    return re.findall(r"[A-Za-z]{2}\[\d\]|[\w\[\]]+", re.sub(r"<[^>]+>", " ", text))


def _index(topic: Topic) -> tuple[set, set, set]:
    def forms(text):
        return {f for w in _words(text) for f in _norm(w)}
    return forms(topic.keywords), forms(topic.title), forms(topic.text)


_INDEX = {t.id: _index(t) for t in TOPICS}


def search(query: str, limit: int = 6) -> list[Topic]:
    """Topics ranked by how well they match a free-text Hebrew/English question."""
    q = {f for w in _words(query) for f in _norm(w)}
    if not q:
        return []
    scored = []
    for t in TOPICS:
        kw, title, text = _INDEX[t.id]
        s = 3 * len(q & kw) + 2 * len(q & title) + len(q & text)
        if s:
            scored.append((s, t))
    scored.sort(key=lambda x: -x[0])
    return [t for _, t in scored[:limit]]


def topic(tid: str) -> Topic | None:
    return next((t for t in TOPICS if t.id == tid), None)


