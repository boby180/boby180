"""PRM parameter files written by the SC-AT Shell ("Upload Controller Parameters").

Format (SC-AT PC Shell manual 4.5.1.7): one assignment per line, comments start with an
apostrophe:
    ' Set KI parameters.
    XKI=8
    YKP[2]=1200
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

AXES = "XYZW"
TUNING_KEYS = ["KP", "KI", "KD", "IS", "ER", "TL", "FF[1]", "FF[2]", "CG"]
# CG bit 3 (zero based) selects the control scheme (Users Manual chapter 6); set = PID, clear = PIV.
CG_PID_BIT = 3

_LINE = re.compile(r"^\s*([A-Z])\s*([A-Z]{2})\s*(?:\[\s*(\d+)\s*\])?\s*=\s*(-?\d+)\s*$")


@dataclass
class PrmFile:
    path: Path | None = None
    values: dict[tuple[str, str], int] = field(default_factory=dict)  # (axis, "KP" / "FF[2]") -> value
    lines: int = 0
    skipped: list[str] = field(default_factory=list)

    def get(self, axis: str, key: str) -> int | None:
        v = self.values.get((axis, key))
        if v is None and key.endswith("[1]"):  # XKP is the same as XKP[1]
            v = self.values.get((axis, key[:-3]))
        if v is None and "[" not in key:
            v = self.values.get((axis, key + "[1]"))
        return v

    def mode(self, axis: str) -> str | None:
        cg = self.get(axis, "CG")
        if cg is None:
            return None
        return "PID" if cg >> CG_PID_BIT & 1 else "PIV"

    def axes(self) -> list[str]:
        return [a for a in AXES if any(k[0] == a for k in self.values)]


def parse_prm(text: str, path: Path | None = None) -> PrmFile:
    prm = PrmFile(path)
    for raw in text.splitlines():
        line = raw.split("'", 1)[0].split("‘", 1)[0].split("’", 1)[0].strip()
        if not line:
            continue
        prm.lines += 1
        for clause in line.split(";"):
            clause = clause.strip()
            if not clause:
                continue
            m = _LINE.match(clause.upper())
            if not m:
                prm.skipped.append(clause)
                continue
            axis, kw, idx, val = m.groups()
            key = f"{kw}[{idx}]" if idx else kw
            prm.values[(axis, key)] = int(val)
    return prm


def load_prm(path: str | Path) -> PrmFile:
    path = Path(path)
    data = path.read_bytes()
    for enc in ("utf-8", "cp1255", "latin-1"):
        try:
            return parse_prm(data.decode(enc), path)
        except UnicodeDecodeError:
            continue
    return parse_prm(data.decode("latin-1", "replace"), path)


def prm_text(changes: dict[tuple[str, str], int], note: str) -> str:
    """A small PRM with only the changed values, for "Download Controller Parameters"."""
    out = ["'", f"' {note}", "' Generated by Tuner 4164. Test one change at a time.", "'"]
    for (axis, key), v in changes.items():
        out.append(f"{axis}{key}={v}")
    return "\r\n".join(out) + "\r\n"
